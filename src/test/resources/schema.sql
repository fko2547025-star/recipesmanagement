-- ==================================================
--  テスト用のテーブル。テストのたびに、メモリ上の空のデータベースに作る（src/test/resources/application.properties）。
--  本番のデータベースと同じ形にしてある：
--    ・created_at などの「今の日時」はデータベースが入れる（DEFAULT CURRENT_TIMESTAMP）
--    ・レシピを消すと、いいね・コメントは一緒に消え（ON DELETE CASCADE）、献立はレシピの欄だけ空になる（ON DELETE SET NULL）
-- ==================================================

-- ユーザー
CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    VARCHAR(50)  NOT NULL UNIQUE,   -- ログイン用のユーザー名
    password    VARCHAR(255) NOT NULL,          -- 暗号化したパスワード
    nickname    VARCHAR(50),                    -- 表示名（任意）
    avatar_path VARCHAR(255),                   -- プロフィール写真のファイル名
    email       VARCHAR(255),                   -- パスワード再設定用
    avoid_foods VARCHAR(200),                   -- アレルギー・苦手な食材（AI に伝える）
    email_verified       BOOLEAN NOT NULL DEFAULT TRUE,  -- メールアドレスの確認が済んだか
    email_verify_token   VARCHAR(64),                    -- 確認メールのリンクのトークンのハッシュ
    email_verify_expires TIMESTAMP,                      -- そのリンクの有効期限
    role                 VARCHAR(20) NOT NULL DEFAULT 'USER',  -- USER か ADMIN（管理者）
    suspended            BOOLEAN NOT NULL DEFAULT FALSE,       -- 利用停止中か
    suspended_reason     VARCHAR(200)                          -- 利用停止の理由（本人に表示する）
);

-- レシピ
CREATE TABLE recipes (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL REFERENCES users (id),
    title        VARCHAR(100) NOT NULL,
    category     VARCHAR(20)  NOT NULL,
    description  VARCHAR(500),
    steps        VARCHAR(4000) NOT NULL,        -- 作り方（1行が1手順）
    memo         VARCHAR(1000),                 -- コツ・ポイント
    servings     INT          NOT NULL DEFAULT 2,
    cooking_time INT,                           -- 調理時間（分）
    difficulty   VARCHAR(10),                   -- かんたん／ふつう／本格
    image_path   VARCHAR(255),
    featured     BOOLEAN NOT NULL DEFAULT FALSE,   -- 管理者が選んだ「おすすめ」
    created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- レシピの材料（レシピを消すと一緒に消える）
CREATE TABLE recipe_ingredients (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id  BIGINT NOT NULL REFERENCES recipes (id) ON DELETE CASCADE,
    name       VARCHAR(255),
    quantity   DOUBLE PRECISION,               -- 少々・適量は空
    unit       VARCHAR(255),
    sort_order INT
);

-- 食材（在庫）
CREATE TABLE ingredients (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users (id),
    name        VARCHAR(255),
    quantity    DOUBLE PRECISION,
    unit        VARCHAR(255),
    category    VARCHAR(20),
    expiry_type VARCHAR(255),                  -- 賞味期限／消費期限
    expiry_date DATE,
    opened_date DATE
);

-- いいね（同じ人が同じレシピに2回いいねできない）
CREATE TABLE likes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users (id),
    recipe_id  BIGINT NOT NULL REFERENCES recipes (id) ON DELETE CASCADE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, recipe_id)
);

-- コメント・つくれぽ
CREATE TABLE comments (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT  NOT NULL REFERENCES users (id),
    recipe_id     BIGINT  NOT NULL REFERENCES recipes (id) ON DELETE CASCADE,
    content       VARCHAR(500),
    image_path    VARCHAR(255),
    cooked_report BOOLEAN NOT NULL DEFAULT FALSE,   -- 「作りました」
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- フォロー（同じ人を2回フォローできない）
CREATE TABLE follows (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    follower_id BIGINT    NOT NULL REFERENCES users (id),   -- フォローする人
    followee_id BIGINT    NOT NULL REFERENCES users (id),   -- フォローされる人
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (follower_id, followee_id)
);

-- 献立（レシピを消すと、レシピの欄だけ空になる）
CREATE TABLE meal_plans (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id   BIGINT  NOT NULL REFERENCES users (id),
    recipe_id BIGINT  REFERENCES recipes (id) ON DELETE SET NULL,
    plan_date DATE,
    meal_type VARCHAR(10),                     -- 朝／昼／夜
    servings  INT,
    memo      VARCHAR(100),
    cooked    BOOLEAN NOT NULL DEFAULT FALSE
);

-- パスワード再設定のトークン（トークンそのものではなく、ハッシュだけを保存する）
CREATE TABLE password_reset_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP   NOT NULL,
    used       BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 通報（レシピかコメントのどちらか一方を通報する）
CREATE TABLE reports (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id BIGINT       NOT NULL REFERENCES users (id),      -- 通報した人
    recipe_id   BIGINT       REFERENCES recipes (id) ON DELETE CASCADE,
    comment_id  BIGINT       REFERENCES comments (id) ON DELETE CASCADE,
    reason      VARCHAR(500) NOT NULL,                            -- 通報の理由
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 管理者の操作の記録（管理者が退会しても記録は残すので、名前も保存する）
CREATE TABLE admin_logs (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id   BIGINT       REFERENCES users (id) ON DELETE SET NULL,
    admin_name VARCHAR(50)  NOT NULL,
    action     VARCHAR(50)  NOT NULL,      -- 何をしたか（例：レシピを削除）
    target     VARCHAR(200),               -- 何に対して（例：「カレー」(id=3)）
    detail     VARCHAR(500),               -- 理由など
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- お知らせ（表示中のものは、全画面の上に帯で出す）
CREATE TABLE announcements (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message    VARCHAR(200) NOT NULL,
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- NGワード（含まれるレシピ・コメント・ニックネームは投稿できない）
CREATE TABLE ng_words (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word       VARCHAR(50) NOT NULL UNIQUE,
    created_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- お問い合わせ（ログインしていなくても送れる。送った人が退会しても残す）
CREATE TABLE inquiries (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT        REFERENCES users (id) ON DELETE SET NULL,
    category   VARCHAR(20)   NOT NULL,                 -- 種類（使い方・不具合・アカウント・その他）
    email      VARCHAR(255)  NOT NULL,                 -- 返信先
    message    VARCHAR(1000) NOT NULL,
    status     VARCHAR(10)   NOT NULL DEFAULT 'OPEN',  -- OPEN（未対応）か DONE（対応済み）
    reply      VARCHAR(2000),                          -- 管理者の返信
    replied_at TIMESTAMP,
    created_at TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

